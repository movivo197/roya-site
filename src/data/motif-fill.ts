function interp(pair: Pair, titleFa: string, titleEn: string): Pair {
  return [pair[0].replaceAll("{t}", titleFa), pair[1].replaceAll("{t}", titleEn)];
}

export function fillFor(
  id: string,
  titleFa: string,
  titleEn: string,
  category: string,
): { fa: Partial<Record<SourceKey, string>>; en: Partial<Record<SourceKey, string>> } {
  const motifName = SYMBOL_MOTIF[id] ?? CAT_MOTIF[category] ?? "mind-sign";
  const motif = MOTIF[motifName] ?? MOTIF["mind-sign"];
  const fa: Partial<Record<SourceKey, string>> = {};
  const en: Partial<Record<SourceKey, string>> = {};
  (Object.keys(motif) as SourceKey[]).forEach((k) => {
    const pair = motif[k];
    if (!pair) return;
    const [a, b] = interp(pair, titleFa, titleEn);
    fa[k] = a;
    en[k] = b;
  });
  return { fa, en };
}
