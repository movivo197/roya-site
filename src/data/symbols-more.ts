function stripNotes(sources: More["sources"]): Partial<Record<SourceKey, string>> {
  const out: Partial<Record<SourceKey, string>> = {};
  const remap: Record<string, SourceKey> = { celtic: "nordic", taoist: "chinese", sufi: "persian" };
  for (const [rawKey, v] of Object.entries(sources)) {
    if (!v) continue;
    const k = (remap[rawKey] ?? rawKey) as SourceKey;
    if ((ALL_SOURCE_KEYS as readonly string[]).includes(k)) out[k] = v;
  }
  return out;
}

